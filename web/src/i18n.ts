const KEY = "rail.lang";

function read(): Lang {
  try {
    return localStorage.getItem(KEY) === "bn" ? "bn" : "en";
  } catch {
    return "en";
  }
}

let current: Lang = read();
const listeners = new Set<(l: Lang) => void>();
if (typeof document !== "undefined") document.documentElement.lang = current;

export const lang = () => current;

/** The Intl locale for dates, times, numbers and money. */
export const locale = () => (current === "bn" ? "bn-BD" : "en-GB");

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {
    /* private mode: the choice just isn't remembered */
  }
  listeners.forEach((f) => f(l));
}

/** Re-renders the caller (App, so the whole page) when the language changes. */
export function useLang(): Lang {
  const [l, set] = useState(current);
  useEffect(() => {
    listeners.add(set);
    return () => {
      listeners.delete(set);
    };
  }, []);
  return l;
}

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";

/** A number (or the digits in a string) in the current language's digits. */
export const num = (n: number | string) =>
  current === "bn" ? String(n).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]) : String(n);

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s: string = current === "bn" ? bn[key] : en[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => {
    const v = vars[k];
    return v === undefined ? m : typeof v === "number" ? num(v) : v;
  });
}

/** For keys built from API codes ("class." + code): the code itself if there is no text for it. */
export function tCode(prefix: string, code: string): string {
  const key = `${prefix}.${code}` as Key;
  return key in en ? t(key) : code;
}
